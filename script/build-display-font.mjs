import { copyFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const packageRoot = path.dirname(require.resolve("@chinese-fonts/lxgwwenkaibright/package.json"));
const sourceRoot = path.join(projectRoot, "src");
const publicRoot = path.join(projectRoot, "public", "fonts", "lxgw-bright");
const cssOutput = path.join(projectRoot, "src", "styles", "lxgw-bright.generated.css");
const family = "Yoyo LXGW Bright";
const variants = [
  { directory: "LXGWBright-Regular", output: "regular", weights: [400] },
  { directory: "LXGWBright-Medium", output: "medium", weights: [500, 600, 700] },
  { directory: "LXGWBright-Italic", output: "italic", weights: [400] },
  { directory: "LXGWBright-MediumItalic", output: "medium-italic", weights: [500, 600, 700] },
];
const sourceExtensions = new Set([".astro", ".css", ".js", ".json", ".mjs", ".svelte", ".ts", ".tsx"]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute));
    else if (entry.isFile()) files.push(absolute);
  }
  return files;
}

function displayTextFromMarkdown(source) {
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)?.[1] || "";
  const displayLines = source
    .split(/\r?\n/)
    .filter((line) => /^#{1,6}\s/.test(line) || /^>\s?/.test(line));
  return `${frontmatter}\n${displayLines.join("\n")}`;
}

function rangesFrom(block) {
  const value = block.match(/unicode-range:([^;}]+)/i)?.[1];
  if (!value) return [];
  return value.split(",").map((part) => {
    const [start, end = start] = part.trim().replace(/^U\+/i, "").split("-");
    return [Number.parseInt(start, 16), Number.parseInt(end, 16)];
  });
}

function intersects(ranges, codepoints) {
  return ranges.some(([start, end]) => {
    for (const codepoint of codepoints) {
      if (codepoint >= start && codepoint <= end) return true;
    }
    return false;
  });
}

const scannedFiles = await walk(sourceRoot);
const fragments = [];
for (const file of scannedFiles) {
  if (file === cssOutput) continue;
  const extension = path.extname(file);
  if (extension !== ".md" && !sourceExtensions.has(extension)) continue;
  const source = await readFile(file, "utf8");
  fragments.push(extension === ".md" ? displayTextFromMarkdown(source) : source);
}

const codepoints = new Set([...fragments.join("\n")].map((character) => character.codePointAt(0)));
const generatedBlocks = [];
let copiedFiles = 0;
let copiedBytes = 0;

await rm(publicRoot, { recursive: true, force: true });
await mkdir(publicRoot, { recursive: true });

for (const variant of variants) {
  const variantRoot = path.join(packageRoot, "dist", variant.directory);
  const css = await readFile(path.join(variantRoot, "result.css"), "utf8");
  const blocks = css.match(/@font-face\{[^}]+\}/g) || [];
  const selected = blocks.filter((block) => intersects(rangesFrom(block), codepoints));
  const outputDirectory = path.join(publicRoot, variant.output);
  await mkdir(outputDirectory, { recursive: true });

  for (const block of selected) {
    const filename = block.match(/url\("\.\/([^"?]+\.woff2)"\)/)?.[1];
    if (!filename) throw new Error(`${variant.directory} 中无法解析字体文件名`);
    const sourceFile = path.join(variantRoot, filename);
    const destination = path.join(outputDirectory, filename);
    await copyFile(sourceFile, destination);
    copiedFiles += 1;
    copiedBytes += (await readFile(sourceFile)).byteLength;

    const webSource = `url("/fonts/lxgw-bright/${variant.output}/${filename}")format("woff2")`;
    const normalized = block
      .replace(/font-family:"[^"]+"/, `font-family:"${family}"`)
      .replace(/src:local\("[^"]+"\),url\("\.\/[^"?]+\.woff2"\)format\("woff2"\)/, `src:${webSource}`);
    for (const weight of variant.weights) {
      generatedBlocks.push(normalized.replace(/font-weight:\d+/, `font-weight:${weight}`));
    }
  }
}

const header = `/* Generated by script/build-display-font.mjs. Do not edit by hand.\n` +
  ` * Source: @chinese-fonts/lxgwwenkaibright 2.0.0 / LXGW Bright 5.526.\n` +
  ` * Only pre-split WOFF2 fragments needed by the site's display text are published. */\n`;
await writeFile(cssOutput, `${header}${generatedBlocks.join("\n")}\n`, "utf8");
await copyFile(path.join(packageRoot, "LICENSE"), path.join(publicRoot, "WEBFONT-PACKAGE-LICENSE.txt"));
await writeFile(
  path.join(publicRoot, "FONT-NOTICE.txt"),
  "LXGW Bright font software is distributed under the SIL Open Font License 1.1.\n" +
    "Font project: https://github.com/lxgw/LxgwBright\n" +
    "Webfont packaging: https://github.com/KonghaYao/chinese-free-web-font-storage\n",
  "utf8",
);

console.log(`展示字体已生成：${copiedFiles} 个 WOFF2 分片，${(copiedBytes / 1024 / 1024).toFixed(2)} MiB，覆盖 ${codepoints.size} 个当前源码字符。`);
